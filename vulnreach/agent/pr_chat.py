"""PR conversation agent for VulnReach.

A conversational agent that debates a vulnerability verdict on a pull request.
The agent answers *only* from evidence in the analysis report, quoting
``file:line`` hops from the call path.  It never claims certainty it does not
have: when dynamic features block proof it says ``uncertain``.

Two backends are supported:

* A pluggable :class:`LLMClient` (you can wire up your own model endpoint).
* A built-in :class:`RuleBasedLLMClient` that works without any LLM, intended
  for demos and offline use.

The agent can re-run the reachability analyzer when a user challenges a
``not_reachable`` verdict on a specific function, and it records user-supplied
assumptions (e.g. ``"that getattr only ever receives 'safe_load'"``) and
re-runs the analysis under those assumptions, stating that the verdict now
depends on them.
"""

from __future__ import annotations

import re
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any

from vulnreach.advisories.fix_commit import FixCommit
from vulnreach.callgraph.builder import CallGraphBuilder, CallGraphResult
from vulnreach.models import Alert, PathHop, Verdict
from vulnreach.reachability.analyzer import ReachabilityAnalyzer


def build_pr_comment(verdict: Verdict) -> str:
    """Format a Markdown PR comment for a verdict (standalone function)."""
    lines: list[str] = []
    lines.append(f"## VulnReach verdict: {verdict.alert.package}@{verdict.alert.version}")
    lines.append("")
    lines.append(f"- **Advisory:** {verdict.alert.advisory_id}")
    if verdict.alert.aliases:
        lines.append(f"- **Aliases:** {', '.join(verdict.alert.aliases)}")
    lines.append(f"- **Verdict:** {verdict.status}")
    lines.append(f"- **Confidence:** {verdict.confidence}")
    lines.append("")
    lines.append("### Explanation")
    lines.append(verdict.explanation or "No explanation recorded.")
    lines.append("")
    lines.append("### Call path")
    if verdict.call_path:
        lines.append("| Hop | File:Line | Function |")
        lines.append("|-----|-----------|----------|")
        for i, hop in enumerate(verdict.call_path, 1):
            lines.append(f"| {i} | {hop.file}:{hop.line} | {hop.function} |")
    else:
        lines.append("*No call path (no static route to the vulnerable code.)*")
    lines.append("")
    if verdict.dynamic_blockers:
        lines.append("### Dynamic blockers")
        for blocker in verdict.dynamic_blockers:
            lines.append(f"- {blocker}")
        lines.append("")
    lines.append("### Suggested action")
    if verdict.status == "reachable":
        lines.append(
            f"Upgrade `{verdict.alert.package}` from `{verdict.alert.version}` to a "
            "patched version. The vulnerable code is reachable from your project."
        )
    elif verdict.status == "not_reachable":
        lines.append(
            "No action required. The vulnerable code is not reachable from your "
            "project code based on static analysis."
        )
    else:
        lines.append(
            "Manual review required. Dynamic Python features could conceal a call "
            "path to the vulnerable code. Confirm the dynamic sites below are not "
            "reachable from user-controlled input."
        )
    lines.append("")
    lines.append("---")
    lines.append("*Generated by VulnReach — static reachability analysis.*")
    return "\n".join(lines)


# ------------------------------------------------------------------ LLM client

class LLMClient(ABC):
    """Pluggable LLM interface.  Implement ``chat`` to hook up a model endpoint."""

    @abstractmethod
    def chat(self, messages: list[dict[str, str]]) -> str:
        """Return the assistant's reply for the given chat messages."""


class RuleBasedLLMClient(LLMClient):
    """Deterministic, evidence-only fallback that needs no LLM or API key.

    Replies are constructed from the verdict's own evidence (call path, dynamic
    blockers, fix-commit resolution) so they are always faithful to the report.
    """

    def __init__(self, agent: "PRChatAgent") -> None:
        self.agent = agent

    def chat(self, messages: list[dict[str, str]]) -> str:
        user_message = ""
        for m in reversed(messages):
            if m.get("role") == "user":
                user_message = m.get("content", "")
                break
        return self.agent._rule_based_reply(user_message)


# ------------------------------------------------------------------ assumptions

@dataclass
class UserAssumption:
    """A user-supplied assumption that the verdict may depend on."""

    assumption: str
    source_message: str
    related_dynamic_site: str | None = None


# ------------------------------------------------------------------ agent

class PRChatAgent:
    """Debate a vulnerability verdict using only report evidence."""

    def __init__(
        self,
        verdict: Verdict,
        analyzer: ReachabilityAnalyzer,
        project_path: str,
        alert: Alert,
        vulnerable_functions: list[Any],
        fix_commit: FixCommit,
        call_graph: CallGraphResult,
        llm_client: LLMClient | None = None,
    ) -> None:
        self.verdict = verdict
        self.analyzer = analyzer
        self.project_path = project_path
        self.alert = alert
        self.vulnerable_functions = vulnerable_functions
        self.fix_commit = fix_commit
        self.call_graph = call_graph
        self.llm_client: LLMClient = llm_client or RuleBasedLLMClient(self)
        self.assumptions: list[UserAssumption] = []
        self.conversation: list[dict[str, str]] = []

    # ------------------------------------------------------------------ public

    def respond(self, user_message: str) -> str:
        """Reply to a user message, using only report evidence.

        Handles three situations:

        * User challenges a ``not_reachable`` verdict on a named function/path
          -> re-run the analyzer for that target and update the answer.
        * User supplies new information about a dynamic feature
          -> record as an assumption, re-run, say the verdict depends on it.
        * General question -> answer from the verdict's evidence.
        """
        self.conversation.append({"role": "user", "content": user_message})

        # Detect a challenge to a not_reachable verdict naming a function.
        challenged_target = self._parse_challenge(user_message)
        if self.verdict.status == "not_reachable" and challenged_target is not None:
            reply = self._handle_challenge(challenged_target)
        else:
            # Detect a user-supplied assumption about a dynamic feature.
            assumption = self._parse_assumption(user_message)
            if assumption is not None:
                self.assumptions.append(assumption)
                reply = self._handle_assumption(assumption)
            else:
                reply = self._general_reply(user_message)

        self.conversation.append({"role": "assistant", "content": reply})
        return reply

    def build_pr_comment(self, verdict: Verdict | None = None) -> str:
        """Format a Markdown PR comment for a verdict."""
        v = verdict or self.verdict
        lines: list[str] = []
        lines.append(f"## VulnReach verdict: {v.alert.package}@{v.alert.version}")
        lines.append("")
        lines.append(f"- **Advisory:** {v.alert.advisory_id}")
        if v.alert.aliases:
            lines.append(f"- **Aliases:** {', '.join(v.alert.aliases)}")
        lines.append(f"- **Verdict:** {v.status}")
        lines.append(f"- **Confidence:** {v.confidence}")
        lines.append(f"- **Fix commit:** {v.reasons[0] if v.reasons else 'not resolved'}")
        lines.append("")
        lines.append("### Explanation")
        lines.append(v.explanation or "No explanation recorded.")
        lines.append("")
        lines.append("### Call path")
        if v.call_path:
            lines.append("| Hop | File:Line | Function |")
            lines.append("|-----|-----------|----------|")
            for i, hop in enumerate(v.call_path, 1):
                lines.append(f"| {i} | {hop.file}:{hop.line} | {hop.function} |")
        else:
            lines.append("*No call path (no static route to the vulnerable code.)*")
        lines.append("")
        if v.dynamic_blockers:
            lines.append("### Dynamic blockers")
            for blocker in v.dynamic_blockers:
                lines.append(f"- {blocker}")
            lines.append("")
        lines.append("### Suggested action")
        if v.status == "reachable":
            lines.append(
                f"Upgrade `{v.alert.package}` from `{v.alert.version}` to a patched "
                "version. The vulnerable code is reachable from your project."
            )
        elif v.status == "not_reachable":
            lines.append(
                "No action required. The vulnerable code is not reachable from your "
                "project code based on static analysis."
            )
        else:
            lines.append(
                "Manual review required. Dynamic Python features could conceal a call "
                "path to the vulnerable code. Confirm the dynamic sites below are not "
                "reachable from user-controlled input."
            )
        lines.append("")
        lines.append("---")
        lines.append("*Generated by VulnReach — static reachability analysis.*")
        return "\n".join(lines)

    # ------------------------------------------------------------------ replies

    def _rule_based_reply(self, user_message: str) -> str:
        """Build a rule-based reply from the verdict evidence."""
        v = self.verdict
        msg_lower = user_message.lower()

        # Status summary
        status_line = {
            "reachable": (
                f"**{v.alert.package}@{v.alert.version} ({v.alert.advisory_id}) is "
                f"REACHABLE** (confidence: {v.confidence})."
            ),
            "not_reachable": (
                f"**{v.alert.package}@{v.alert.version} ({v.alert.advisory_id}) is "
                f"NOT reachable** (confidence: {v.confidence})."
            ),
            "uncertain": (
                f"**{v.alert.package}@{v.alert.version} ({v.alert.advisory_id}) is "
                f"UNCERTAIN** (confidence: {v.confidence})."
            ),
        }[v.status]

        parts: list[str] = [status_line, ""]

        # Call path evidence
        if v.call_path:
            parts.append("Call path (file:line per hop):")
            for hop in v.call_path:
                parts.append(f"  * {hop.file}:{hop.line} — {hop.function}")
            parts.append("")

        # Dynamic blockers
        if v.dynamic_blockers:
            parts.append("Dynamic features that could hide a path:")
            for blocker in v.dynamic_blockers:
                parts.append(f"  * {blocker}")
            parts.append("")

        # Assumptions
        if self.assumptions:
            parts.append("User-asserted assumptions this verdict depends on:")
            for a in self.assumptions:
                parts.append(f"  * {a.assumption}  (from: “{a.source_message}”)")
            parts.append("")

        # Fix commit
        parts.append(
            f"Fix commit resolution: {self.fix_commit.resolution_method} "
            f"(confidence {self.fix_commit.confidence})."
        )
        if self.fix_commit.sha:
            parts.append(f"Fix commit SHA: {self.fix_commit.sha}.")
        parts.append("")

        # Specific replies
        if v.status == "reachable":
            parts.append(
                "I cannot mark this safe: a static call path leads from your code "
                "to the vulnerable function. Upgrade the package."
            )
        elif v.status == "not_reachable":
            parts.append(
                "No static call path reaches the vulnerable function, and no dynamic "
                "features were found that could hide one. If you believe a path exists, "
                "name the function or file and I will re-check."
            )
        else:
            parts.append(
                "I cannot rule out reachability: dynamic Python features could conceal "
                "a path to the vulnerable code. Treat this as needing manual review."
            )

        return "\n".join(parts)

    def _general_reply(self, user_message: str) -> str:
        """Answer a general question from the verdict evidence only."""
        return self._rule_based_reply(user_message)

    # ------------------------------------------------------------------ challenges

    def _parse_challenge(self, user_message: str) -> str | None:
        """Return a named function/path if the user challenges not_reachable."""
        low = user_message.lower()
        if not any(w in low for w in ("reachable", "wrong", "incorrect", "disagree", "path")):
            return None
        # Look for a function-like name or file:line reference.
        m = re.search(r"\b([A-Za-z_][A-Za-z0-9_.]*\.[A-Za-z_][A-Za-z0-9_]*)\b", user_message)
        if m:
            return m.group(1)
        m = re.search(r"([A-Za-z0-9_./-]+\.py)(?::(\d+))?", user_message)
        if m:
            return m.group(1)
        return None

    def _handle_challenge(self, target: str) -> str:
        """Re-run reachability for the named target and update the answer."""
        v = self.verdict
        target_node = self._find_target_node(target)
        if target_node is None:
            return (
                f"I could not find `{target}` in the call graph, so I cannot re-check it. "
                f"The current verdict ({v.status}) stands based on the evidence in the report."
            )

        # Re-run: shortest path from any entry point to this target.
        import networkx as nx

        best_path: list[Any] | None = None
        for entry in self.analyzer.entry_points:
            try:
                path = nx.shortest_path(self.analyzer.graph, entry, target_node)
            except Exception:
                continue
            if best_path is None or len(path) < len(best_path):
                best_path = path

        if best_path:
            hops = [
                PathHop(file=n.file, line=n.line, function=n.qualname)
                for n in best_path
            ]
            over_approx = any(
                self.analyzer.graph[best_path[i]][best_path[i + 1]].get("over_approx", False)
                for i in range(len(best_path) - 1)
            )
            confidence = "medium" if over_approx else "high"
            self.verdict = Verdict(
                alert=self.alert,
                status="reachable",
                confidence=confidence,
                call_path=hops,
                reasons=[f"Reachable via {target} after user challenge"],
                dynamic_blockers=[],
                explanation=(
                    f"Reachable: {self.alert.package}@{self.alert.version} "
                    f"({self.alert.advisory_id}) — re-checking {target} found a static "
                    f"call path to the vulnerable function."
                ),
            )
            lines = [
                f"You're right to challenge that — re-checking `{target}` **does** find a "
                f"reachable path (confidence: {confidence}):",
            ]
            for hop in hops:
                lines.append(f"  * {hop.file}:{hop.line} — {hop.function}")
            lines.append("")
            lines.append(
                f"I have updated the verdict to **reachable**. "
                f"Consider upgrading `{self.alert.package}`."
            )
            return "\n".join(lines)

        # Still no path — but check dynamic sites.
        blockers = [str(s) for s in self.analyzer.dynamic_sites]
        if blockers:
            return (
                f"I re-checked `{target}` and still found no static call path, but "
                f"dynamic features exist in the codebase ({', '.join(set(s.kind for s in self.analyzer.dynamic_sites))}). "
                f"I cannot rule out a hidden path, so the verdict stays **uncertain**, "
                f"not not_reachable."
            )

        return (
            f"I re-checked `{target}` and confirm: no static call path reaches it, and "
            f"no dynamic features could hide one. The verdict (**{v.status}**, "
            f"confidence {v.confidence}) stands."
        )

    # ------------------------------------------------------------------ assumptions

    def _parse_assumption(self, user_message: str) -> UserAssumption | None:
        """Detect a user-supplied assumption about a dynamic feature."""
        low = user_message.lower()
        triggers = ("only ever", "always", "never", "is always", "only receives",
                    "only calls", "only returns", "assume", "assuming")
        if not any(t in low for t in triggers):
            return None
        # Try to link to a dynamic site.
        related = None
        for site in self.analyzer.dynamic_sites:
            if site.kind.lower() in low or site.file.split("/")[-1] in low:
                related = str(site)
                break
        return UserAssumption(
            assumption=user_message,
            source_message=user_message,
            related_dynamic_site=related,
        )

    def _handle_assumption(self, assumption: UserAssumption) -> str:
        """Re-run analysis under the user's assumption and state the dependency."""
        # Re-run: if the assumption addresses the only dynamic blocker, we may
        # move from uncertain to not_reachable — but only with the caveat.
        v = self.verdict
        still_blockers = [
            s for s in self.analyzer.dynamic_sites
            if assumption.related_dynamic_site and str(s) != assumption.related_dynamic_site
        ] or ([] if assumption.related_dynamic_site else list(self.analyzer.dynamic_sites))

        if v.status == "uncertain" and not still_blockers and not v.call_path:
            # The assumption removes the only blocker and there's no static path.
            self.verdict = Verdict(
                alert=self.alert,
                status="not_reachable",
                confidence="medium",
                call_path=[],
                reasons=[
                    "No static call path",
                    f"Verdict depends on user assumption: {assumption.assumption}",
                ],
                dynamic_blockers=[],
                explanation=(
                    f"Not reachable: no static path, and the only dynamic blocker is "
                    f"addressed by the user assumption “{assumption.assumption}”. "
                    f"This verdict depends on that assumption being true."
                ),
            )
            return (
                f"Under your assumption (“{assumption.assumption}”), the only dynamic "
                f"blocker is addressed and there is no static call path. I have updated "
                f"the verdict to **not_reachable**, but **this depends on your "
                f"assumption being true** — if it is not, the verdict reverts to "
                f"uncertain."
            )

        return (
            f"I have recorded your assumption: “{assumption.assumption}”. "
            f"The current verdict ({v.status}) now **depends on this assumption**. "
            f"If the assumption does not hold, dynamic features could still conceal a "
            f"path to the vulnerable code, and the verdict would be uncertain."
        )

    # ------------------------------------------------------------------ helpers

    def _find_target_node(self, target: str) -> Any | None:
        """Find a graph node matching ``target`` (qualname or file:line)."""
        # Direct qualname match
        for node in self.analyzer.graph.nodes:
            if node.qualname == target or node.qualname.endswith("." + target):
                return node
        # file:line match
        m = re.match(r"^(.*?):(\d+)$", target)
        if m:
            file_part, line_part = m.group(1), int(m.group(2))
            for node in self.analyzer.graph.nodes:
                if node.file == file_part and node.line == line_part:
                    return node
        # Short name match (last component)
        for node in self.analyzer.graph.nodes:
            if node.qualname.split(".")[-1] == target:
                return node
        return None
